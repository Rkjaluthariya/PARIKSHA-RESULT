/**
 * Intelligent string translation helper for static UI texts.
 * Handles exact matches, lowercase normalized matches, and fallback.
 */
export const getTranslation = (text: string, lang: 'en' | 'hi' = 'en'): string => {
  if (!text) return '';
  if (lang === 'en') {
    const entry = UI_TRANSLATIONS[text];
    return entry?.en || text;
  }

  // Exact lookup
  if (UI_TRANSLATIONS[text]) {
    return UI_TRANSLATIONS[text].hi;
  }

  // Trimmed lookup
  const trimmed = text.trim();
  if (UI_TRANSLATIONS[trimmed]) {
    return UI_TRANSLATIONS[trimmed].hi;
  }

  // Case-insensitive lookup
  const lower = trimmed.toLowerCase();
  for (const key of Object.keys(UI_TRANSLATIONS)) {
    if (key.toLowerCase() === lower) {
      return UI_TRANSLATIONS[key].hi;
    }
  }

  return text;
};
